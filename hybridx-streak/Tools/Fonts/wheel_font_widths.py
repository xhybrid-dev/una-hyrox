#!/usr/bin/env python3
"""Writes the GUI's WheelFontWidths.hpp: the advance widths of the wheel menu's
fonts, from the committed LVGL font files (assets/fonts/poppins_*.c).

The wheel (the SDK's WheelMenu) sets a row in SemiBold 25 and its tip in
Italic 18, each on a 240 px label that wraps a long line. The family
dashboard's words (DashWords) pick a wording that fits by these widths
(NOTES "S7"), and the training load graphs' legends and dates are held to
theirs (NOTES "S8"). The fonts have no kerning, so a sum of advances is exact.

Run it after the fonts change:
    python3 hybridx-streak/Tools/Fonts/wheel_font_widths.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONTS = ROOT / "Software/Apps/LVGL-GUI/assets/fonts"
OUT = ROOT / "Software/Apps/LVGL-GUI/gui/include/gui/copy/WheelFontWidths.hpp"
FACES = [("kItalic18", "poppins_italic_18.c", "Poppins Italic 18 (a row's tip, and screen titles)"),
         ("kSemiBold25", "poppins_semibold_25.c", "Poppins SemiBold 25 (a row's label)"),
         ("kRegular16", "poppins_regular_16.c", "Poppins Regular 16 (the graphs' legends, NOTES \"S8\")"),
         ("kRegular14", "poppins_regular_14.c", "Poppins Regular 14 (the graphs' scale and dates)")]


def widths(path):
    text = path.read_text()
    adv = [int(m) for m in re.findall(r"\.adv_w = (\d+)", text)]
    cmaps = re.findall(r"\.range_start = (\d+), \.range_length = (\d+), \.glyph_id_start = (\d+)", text)
    table = {}
    for start, length, gid in cmaps:
        for i in range(int(length)):
            table[int(start) + i] = adv[int(gid) + i]
    if text.count("kern_dsc = NULL") != 1:
        raise SystemExit(f"{path.name}: kerning present; sums would not be exact")
    ascii_ = [table[c] for c in range(0x20, 0x7F)]
    dot = table.get(0xB7, max(ascii_))
    return ascii_, dot


lines = ["/**",
         " * Advance widths of the wheel menu's fonts, in 1/16 px, generated by",
         " * Tools/Fonts/wheel_font_widths.py from assets/fonts (do not edit by hand).",
         " * Printable ASCII 0x20..0x7E, then U+00B7 MIDDLE DOT. No kerning: a sum is exact.",
         " */",
         "",
         "#ifndef STREAK_WHEEL_FONT_WIDTHS_HPP",
         "#define STREAK_WHEEL_FONT_WIDTHS_HPP",
         "",
         "#include <cstdint>",
         "",
         "namespace WheelFontWidths",
         "{",
         ""]
for name, file, what in FACES:
    a, dot = widths(FONTS / file)
    lines.append(f"/// {what}.")
    lines.append(f"inline constexpr uint16_t {name}[96] = {{")
    vals = a + [dot]
    for i in range(0, len(vals), 12):
        lines.append("    " + ", ".join(f"{v:3d}" for v in vals[i:i + 12]) + ",")
    lines.append("};")
    lines.append("")
lines += ["} // namespace WheelFontWidths", "", "#endif // STREAK_WHEEL_FONT_WIDTHS_HPP", ""]
OUT.write_text("\n".join(lines))
print(f"wrote {OUT.relative_to(ROOT)}")
